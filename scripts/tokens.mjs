import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export function readJson(path) {
  return JSON.parse(readFileSync(join(root, path), "utf8"));
}

export function flatten(value, prefix = "", out = {}) {
  if (value && typeof value === "object" && !Array.isArray(value)) {
    for (const [key, child] of Object.entries(value)) {
      const path = prefix ? `${prefix}.${key}` : key;
      flatten(child, path, out);
    }
    return out;
  }
  out[prefix] = value;
  return out;
}

export function rawValues(theme) {
  return flatten({
    color: theme.color,
    font: theme.font,
    space: theme.space,
    radius: theme.radius,
    motion: theme.motion,
    size: theme.size,
  });
}

const reference = /^\{([a-zA-Z0-9.]+)\}$/;

export function resolveRef(ref, raw) {
  const match = reference.exec(String(ref));
  if (!match) {
    throw new Error(`Bad reference ${ref}`);
  }
  const path = match[1];
  if (!(path in raw)) {
    throw new Error(`Missing raw token ${path}`);
  }
  return raw[path];
}

export function cssName(token) {
  const kebab = token.replaceAll(".", "-").replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
  return `--${kebab}`;
}

export function renderThemes() {
  const semantic = readJson("tokens/semantic.json");
  const themeNames = ["neutral", "okvy"];
  const modeNames = ["light", "dark"];
  let css = "/* Generated by scripts/build-tokens.mjs. Do not edit. */\n";

  for (const themeName of themeNames) {
    const raw = rawValues(readJson(`themes/${themeName}.json`));
    for (const modeName of modeNames) {
      const mode = readJson(`tokens/modes/${modeName}.json`);
      for (const key of Object.keys(mode)) {
        if (!(key in semantic)) {
          throw new Error(`${modeName} remaps unknown token ${key}`);
        }
      }
      css += `\n[data-theme="${themeName}"][data-mode="${modeName}"] {\n`;
      for (const [name, spec] of Object.entries(semantic)) {
        const value = resolveRef(mode[name] ?? spec.value, raw);
        css += `  ${cssName(name)}: ${value};\n`;
      }
      css += "}\n";
    }
  }

  return css;
}
